import { APIRequestContext } from '@playwright/test';
import { AddStatutoryTimeFrameEventType } from '../../../exui-event-types';
import { exui_triggerEvent, exui_submitEvent } from '../../../utils/api-requests-utils';

export class StatutoryTimeFrameApi {
  private apiContext: APIRequestContext;

  constructor(apiContext: APIRequestContext) {
    this.apiContext = apiContext;
  }

  private readonly eventName = 'addStatutoryTimeframe24Weeks';

  public async submitEvent(options: AddStatutoryTimeFrameEventType): Promise<void> {
    const triggerResponse = await exui_triggerEvent({ apiContext: this.apiContext, caseId: options.caseId, eventName: this.eventName });

    await exui_submitEvent({
      apiContext: this.apiContext,
      caseId: options.caseId,
      eventName: this.eventName,
      eventToken: triggerResponse.eventToken,
      payload: {
        stf24wCurrentReasonAutoGenerated: options.reasonForAddingStatutoryTimeFrame,
      },
    });
  }
}
