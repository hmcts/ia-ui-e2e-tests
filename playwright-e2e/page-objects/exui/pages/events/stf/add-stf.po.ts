import { Page, Locator, expect } from '@playwright/test';
import { ExuiBase } from '../../../exui-base';

export class addStf extends ExuiBase {
  constructor(page: Page) {
    super(page);
  }

  public readonly $interactive = {
    submitButton: this.page.getByRole('button', { name: 'Submit', exact: true }),
    previousButton: this.$commonElements.previousButton,
    cancelButton: this.$commonElements.cancelButton,
    continueButton: this.$commonElements.continueButton,
    closeAndReturnButton: this.$commonElements.closeAndReturnToCaseDetailsButton
  } as const satisfies Record<string, Locator>;

  public readonly $static = {
    pageHeading: this.page.getByRole('heading', { level: 1, name: 'Add Statutory Timeframe', exact: true }),
    caseRecordHeading: this.page.getByRole('heading', { level: 1, name: 'Case record for' }),
    stfReasonTitle: this.page.locator('#content > exui-case-details-home > ccd-case-event-trigger > div > ccd-case-edit > ccd-case-edit-submit > div > form > div.ng-star-inserted > table.form-table.ng-star-inserted > tbody > tr > th > span'),
    addStfReason: this.page.locator('#stf24wCurrentReasonAutoGenerated')
  } as const satisfies Record<string, Locator>;

  public async addStfReason() {
    await this.$static.addStfReason.fill('Add STF reason TEST');
  }

  public async verifyUserIsOnPage(): Promise<void> {
    await this.verifyUserIsOnExpectedPage({
      urlPath: 'trigger/addStatutoryTimeframe24Weeks/addStatutoryTimeframe24WeeksaddStatutoryTimeframe24Weeks',
      pageHeading: this.$static.pageHeading,
    });
  }

  public async verifyAllTextOnPage(): Promise<void> {
    await Promise.all([
      expect(this.$static.caseRecordHeading).toBeVisible(),
      expect(this.$static.stfReasonTitle).toHaveText('Reason'),
      expect(this.$static.stfReasonTitle).toBeVisible(),
    ]);
  }

  public async submitEvent(): Promise<void> {
    await this.$static.addStfReason.fill('Add STF AT');
    await this.navigationClick(this.$interactive.continueButton);
    await this.verifyAllTextOnPage();
    await this.navigationClick(this.$interactive.submitButton);
    await this.navigationClick(this.$interactive.closeAndReturnButton);
  }
}