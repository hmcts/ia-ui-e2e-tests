import { expect, Locator, Page } from '@playwright/test';
import { ExuiBase } from '../../../../exui-base';

export class AddStatutoryTimeFramePage extends ExuiBase {
  constructor(page: Page) {
    super(page);
  }

  public readonly $inputs = {
    reason: this.page.locator('input[id="stf24wCurrentReasonAutoGenerated"]'),
  } as const satisfies Record<string, Locator>;

  public readonly $interactive = {
    continueButton: this.$commonElements.continueButton,
    previousButton: this.$commonElements.previousButton,
    cancelButton: this.$commonElements.cancelButton,
  } as const satisfies Record<string, Locator>;

  public readonly $static = {
    pageHeading: this.page.getByRole('heading', { level: 1, name: 'Add Statutory Timeframe', exact: true }),
    caseRecordHeading: this.$commonElements.caseRecordHeading,
    reasonLabel: this.page.locator('label[for="stf24wCurrentReasonAutoGenerated"] .form-label'),
  } as const satisfies Record<string, Locator>;

  public async verifyUserIsOnPage(): Promise<void> {
    await this.verifyUserIsOnExpectedPage({
      urlPath: 'trigger/addStatutoryTimeframe24Weeks/addStatutoryTimeframe24WeeksaddStatutoryTimeframe24Weeks',
      pageHeading: this.$static.pageHeading,
    });
  }

  public async verifyAllTextOnPage(): Promise<void> {
    await Promise.all([
      expect(this.$static.caseRecordHeading).toBeVisible(),
      expect(this.$static.reasonLabel).toBeVisible(),
      expect(this.$static.reasonLabel).toHaveText('Reason'),
    ]);
  }

  public async completePageAndContinue(options: { reason: string }): Promise<void> {
    await this.$inputs.reason.fill(options.reason);
    await this.navigationClick(this.$interactive.continueButton);
  }
}
